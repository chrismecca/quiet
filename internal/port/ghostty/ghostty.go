// Package ghostty serializes Quiet's generic terminal palette into Ghostty's
// native theme format.
package ghostty

import (
	"fmt"
	"io"
	"strings"

	"github.com/chrismecca/quiet/internal/color"
	"github.com/chrismecca/quiet/internal/port/terminal"
)

// Encode writes one resolved generic terminal palette as a Ghostty theme.
//
// This package contains no Quiet color policy. All semantic mapping and ANSI
// derivation occur in terminal.Resolve before the palette reaches this
// serializer.
func Encode(
	w io.Writer,
	p terminal.Palette,
) error {
	background, err := hex(
		"background",
		p.Background,
	)
	if err != nil {
		return err
	}

	foreground, err := hex(
		"foreground",
		p.Text,
	)
	if err != nil {
		return err
	}

	cursor, err := hex(
		"cursor",
		p.Cursor,
	)
	if err != nil {
		return err
	}

	selection, err := hex(
		"selection",
		p.Selection,
	)
	if err != nil {
		return err
	}

	var b strings.Builder

	fmt.Fprintf(
		&b,
		"# Generated by quiet port ghostty. Do not edit.\n"+
			"#\n"+
			"# %s\n\n",
		p.Name,
	)

	for i, value := range p.ANSI {
		valueHex, err := hex(
			fmt.Sprintf(
				"ANSI %d",
				i,
			),
			value,
		)
		if err != nil {
			return err
		}

		fmt.Fprintf(
			&b,
			"palette = %d=%s\n",
			i,
			valueHex,
		)
	}

	fmt.Fprintf(
		&b,
		"\n"+
			"background = %s\n"+
			"foreground = %s\n"+
			"cursor-color = %s\n"+
			"cursor-text = %s\n"+
			"selection-background = %s\n"+
			"selection-foreground = %s\n",
		background,
		foreground,
		cursor,
		background,
		selection,
		foreground,
	)

	if _, err := io.WriteString(
		w,
		b.String(),
	); err != nil {
		return fmt.Errorf(
			"write Ghostty theme: %w",
			err,
		)
	}

	return nil
}

func hex(
	name string,
	value color.SRGB,
) (string, error) {
	result, err := value.Hex()
	if err != nil {
		return "", fmt.Errorf(
			"%s: %w",
			name,
			err,
		)
	}

	return result, nil
}
