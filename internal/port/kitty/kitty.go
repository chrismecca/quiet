// Package kitty serializes quiet's generic terminal palette into kitty's
// native color configuration format.
package kitty

import (
	"fmt"
	"io"
	"strings"

	"github.com/chrismecca/quiet/internal/color"
	"github.com/chrismecca/quiet/internal/port/terminal"
)

// Encode writes one resolved generic terminal palette as a kitty theme.
//
// This package contains no quiet color derivation. Semantic mapping and ANSI
// derivation occur in terminal.Resolve before the palette reaches this
// serializer.
func Encode(
	w io.Writer,
	p terminal.Palette,
) error {
	background, err := hex(
		"background",
		p.Background,
	)
	if err != nil {
		return err
	}

	foreground, err := hex(
		"foreground",
		p.Text,
	)
	if err != nil {
		return err
	}

	cursor, err := hex(
		"cursor",
		p.Cursor,
	)
	if err != nil {
		return err
	}

	selection, err := hex(
		"selection",
		p.Selection,
	)
	if err != nil {
		return err
	}

	var b strings.Builder

	fmt.Fprintf(
		&b,
		"# Generated by quiet port kitty. Do not edit.\n"+
			"#\n"+
			"# %s\n\n",
		p.Name,
	)

	fmt.Fprintf(
		&b,
		"foreground            %s\n"+
			"background            %s\n"+
			"\n"+
			"cursor                %s\n"+
			"cursor_text_color     %s\n"+
			"\n"+
			"selection_foreground  %s\n"+
			"selection_background  %s\n"+
			"\n"+
			"url_color             %s\n"+
			"\n",
		foreground,
		background,
		cursor,
		background,
		foreground,
		selection,
		cursor,
	)

	for i, value := range p.ANSI {
		valueHex, err := hex(
			fmt.Sprintf(
				"ANSI %d",
				i,
			),
			value,
		)
		if err != nil {
			return err
		}

		fmt.Fprintf(
			&b,
			"color%-2d               %s\n",
			i,
			valueHex,
		)
	}

	if _, err := io.WriteString(
		w,
		b.String(),
	); err != nil {
		return fmt.Errorf(
			"write kitty theme: %w",
			err,
		)
	}

	return nil
}

func hex(
	name string,
	value color.SRGB,
) (string, error) {
	result, err := value.Hex()
	if err != nil {
		return "", fmt.Errorf(
			"%s: %w",
			name,
			err,
		)
	}

	return result, nil
}
