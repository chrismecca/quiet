// Package dircolors maps filesystem semantics onto Quiet's generic ANSI
// terminal color model using the GNU dircolors configuration format.
package dircolors

import (
	"fmt"
	"io"
)

type entry struct {
	keyword string
	sgr     string
}

type group struct {
	comment string
	entries []entry
}

var groups = []group{
	{
		comment: "Base behavior. Ordinary files remain terminal-default text.",
		entries: []entry{
			{"RESET", "0"},
			{"NORMAL", "0"},
			{"FILE", "0"},
			{"MULTIHARDLINK", "0"},
		},
	},
	{
		comment: "Navigation and execution.",
		entries: []entry{
			{"DIR", "34"},
			{"LINK", "36"},
			{"EXEC", "32"},
		},
	},
	{
		comment: "Special filesystem objects.",
		entries: []entry{
			{"FIFO", "33"},
			{"SOCK", "35"},
			{"DOOR", "35"},
			{"BLK", "33"},
			{"CHR", "33"},
		},
	},
	{
		comment: "Broken or unavailable paths.",
		entries: []entry{
			{"ORPHAN", "31"},
			{"MISSING", "31"},
		},
	},
	{
		comment: "Privilege and writable state. Bold provides a non-hue cue.",
		entries: []entry{
			{"SETUID", "01;31"},
			{"SETGID", "01;31"},
			{"CAPABILITY", "01;31"},
			{"STICKY_OTHER_WRITABLE", "01;33"},
			{"OTHER_WRITABLE", "01;31"},
			{"STICKY", "33"},
		},
	},
}

// Encode writes the generic Quiet GNU dircolors configuration.
//
// The output contains ANSI semantic slot references rather than concrete
// colors. The active Quiet terminal palette supplies the actual Day or Night
// values for those slots.
func Encode(
	w io.Writer,
) error {
	if _, err := io.WriteString(
		w,
		"# Generated by quiet port dircolors. Do not edit.\n"+
			"#\n"+
			"# This file selects semantic ANSI slots from Quiet's generic\n"+
			"# terminal model. It contains no RGB values and is shared by\n"+
			"# Quiet Day and Quiet Night.\n",
	); err != nil {
		return fmt.Errorf(
			"write dircolors header: %w",
			err,
		)
	}

	for _, group := range groups {
		if _, err := fmt.Fprintf(
			w,
			"\n# %s\n",
			group.comment,
		); err != nil {
			return fmt.Errorf(
				"write dircolors group: %w",
				err,
			)
		}

		for _, entry := range group.entries {
			if _, err := fmt.Fprintf(
				w,
				"%s %s\n",
				entry.keyword,
				entry.sgr,
			); err != nil {
				return fmt.Errorf(
					"write dircolors %s: %w",
					entry.keyword,
					err,
				)
			}
		}
	}

	return nil
}
