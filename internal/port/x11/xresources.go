// Package x11 maps Quiet Core semantics onto the X Toolkit resource model.
package x11

import (
	"fmt"
	"io"

	"github.com/chrismecca/quiet/internal/color"
	"github.com/chrismecca/quiet/internal/core"
)

// Palette is the resolved Quiet mapping used by the generic Xt/Xaw resource
// port.
//
// X resources are host roles. They are not additional Quiet Core semantics.
type Palette struct {
	Name string

	Field     color.SRGB
	Surface   color.SRGB
	Structure color.SRGB
	Ink       color.SRGB
	Line      color.SRGB
	Mineral   color.SRGB
}

// Resolve maps one canonical Quiet palette onto the generic Xt/Xaw resource
// vocabulary used by the X11 reference port.
func Resolve(
	p core.Palette,
) Palette {
	return Palette{
		Name: p.Name,

		Field:     p.Anchors.Field,
		Surface:   p.Anchors.Surface,
		Structure: p.Anchors.Structure,
		Ink:       p.Anchors.Ink,
		Line:      p.Anchors.Line,
		Mineral:   p.Anchors.Mineral,
	}
}

// EncodeXResources writes an X resource database fragment suitable for xrdb
// or as the basis of an application-specific Xt app-defaults file.
func EncodeXResources(
	w io.Writer,
	p Palette,
) error {
	field, err := hex(
		"Field",
		p.Field,
	)
	if err != nil {
		return err
	}

	surface, err := hex(
		"Surface",
		p.Surface,
	)
	if err != nil {
		return err
	}

	structure, err := hex(
		"Structure",
		p.Structure,
	)
	if err != nil {
		return err
	}

	ink, err := hex(
		"Ink",
		p.Ink,
	)
	if err != nil {
		return err
	}

	line, err := hex(
		"Line",
		p.Line,
	)
	if err != nil {
		return err
	}

	mineral, err := hex(
		"Mineral",
		p.Mineral,
	)
	if err != nil {
		return err
	}

	if _, err := fmt.Fprintf(
		w,
		"! Generated by quiet port x11. Do not edit.\n"+
			"!\n"+
			"! %s\n"+
			"!\n"+
			"! Generic Xt resource classes.\n"+
			"*Background: %s\n"+
			"*Foreground: %s\n"+
			"*BorderColor: %s\n"+
			"\n"+
			"! Common Athena widget classes.\n"+
			"*Command.background: %s\n"+
			"*Toggle.background: %s\n"+
			"*MenuButton.background: %s\n"+
			"*SimpleMenu.background: %s\n"+
			"*SmeLine.foreground: %s\n"+
			"\n"+
			"! Scrollbar track and active thumb.\n"+
			"*Scrollbar.background: %s\n"+
			"*Scrollbar.foreground: %s\n",
		p.Name,
		field,
		ink,
		line,
		surface,
		surface,
		structure,
		surface,
		line,
		structure,
		mineral,
	); err != nil {
		return fmt.Errorf(
			"write X resources: %w",
			err,
		)
	}

	return nil
}

func hex(
	name string,
	value color.SRGB,
) (string, error) {
	result, err := value.Hex()
	if err != nil {
		return "", fmt.Errorf(
			"%s: %w",
			name,
			err,
		)
	}

	return result, nil
}
