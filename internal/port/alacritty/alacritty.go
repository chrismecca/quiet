// Package alacritty maps quiet's generic terminal palette onto Alacritty's
// TOML color configuration.
//
// Terminal colors come from terminal.Resolve, as in quiet's other terminal
// ports. Alacritty also colors search matches, hint labels, and its footer
// bar; those take quiet roles directly.
package alacritty

import (
	"fmt"
	"io"
	"strings"

	"github.com/chrismecca/quiet/internal/color"
	"github.com/chrismecca/quiet/internal/core"
	"github.com/chrismecca/quiet/internal/port/terminal"
)

// cellForeground keeps the color of the cell beneath a highlight.
const cellForeground = "CellForeground"

var ansiNames = [8]string{
	"black",
	"red",
	"green",
	"yellow",
	"blue",
	"magenta",
	"cyan",
	"white",
}

// pair is a foreground and background in one Alacritty color table.
type pair struct {
	key        string
	foreground string
	background string
}

// Encode writes one quiet palette as an Alacritty color configuration.
func Encode(
	w io.Writer,
	p core.Palette,
) error {
	term, err := terminal.Resolve(p)
	if err != nil {
		return fmt.Errorf(
			"resolve terminal palette: %w",
			err,
		)
	}

	derived, err := core.Derive(p)
	if err != nil {
		return fmt.Errorf(
			"derive quiet roles: %w",
			err,
		)
	}

	a := p.Anchors

	hexes := map[string]color.SRGB{
		"background":   term.Background,
		"foreground":   term.Text,
		"cursor":       term.Cursor,
		"selection":    term.Selection,
		"muted":        a.Muted,
		"structure":    a.Structure,
		"mineral":      a.Mineral,
		"mineral wash": derived.Wash.Mineral.Line,
	}

	hex := map[string]string{}
	for name, c := range hexes {
		h, err := c.Hex()
		if err != nil {
			return fmt.Errorf(
				"%s: %w",
				name,
				err,
			)
		}

		hex[name] = h
	}

	var b strings.Builder

	fmt.Fprintf(
		&b,
		"# Generated by quiet port alacritty. Do not edit.\n"+
			"#\n"+
			"# %s\n\n",
		p.Name,
	)

	fmt.Fprintf(
		&b,
		"[colors.primary]\n"+
			"background = %q\n"+
			"foreground = %q\n"+
			"dim_foreground = %q\n\n",
		hex["background"],
		hex["foreground"],
		hex["muted"],
	)

	// The cursor follows the generic terminal mapping; vi mode uses the
	// same cursor.
	for _, table := range []string{"cursor", "vi_mode_cursor"} {
		fmt.Fprintf(
			&b,
			"[colors.%s]\n"+
				"text = %q\n"+
				"cursor = %q\n\n",
			table,
			hex["background"],
			hex["cursor"],
		)
	}

	fmt.Fprintf(
		&b,
		"[colors.selection]\n"+
			"text = %q\n"+
			"background = %q\n\n",
		hex["foreground"],
		hex["selection"],
	)

	// Search matches take the Mineral line wash and keep each cell's own
	// color; the focused match and hint labels are Field on Mineral.
	pairs := []pair{
		{"search.matches", cellForeground, hex["mineral wash"]},
		{"search.focused_match", hex["background"], hex["mineral"]},
		{"hints.start", hex["background"], hex["mineral"]},
		{"hints.end", hex["foreground"], hex["selection"]},
		{"line_indicator", hex["muted"], hex["structure"]},
		{"footer_bar", hex["foreground"], hex["structure"]},
	}

	for _, pr := range pairs {
		fmt.Fprintf(
			&b,
			"[colors.%s]\n"+
				"foreground = %q\n"+
				"background = %q\n\n",
			pr.key,
			pr.foreground,
			pr.background,
		)
	}

	for bank, table := range []string{"normal", "bright"} {
		fmt.Fprintf(&b, "[colors.%s]\n", table)

		for i, name := range ansiNames {
			h, err := term.ANSI[bank*8+i].Hex()
			if err != nil {
				return fmt.Errorf(
					"ANSI %d: %w",
					bank*8+i,
					err,
				)
			}

			fmt.Fprintf(&b, "%s = %q\n", name, h)
		}

		if bank == 0 {
			b.WriteString("\n")
		}
	}

	if _, err := io.WriteString(
		w,
		b.String(),
	); err != nil {
		return fmt.Errorf(
			"write Alacritty theme: %w",
			err,
		)
	}

	return nil
}
