func writeHighlight(
	b *strings.Builder,
	h highlight,
) {
	if h.link != "" {
		fmt.Fprintf(
			b,
			"set(0, %q, { link = %q })\n",
			h.group,
			h.link,
		)

		return
	}

	var attrs []string

	if h.fg != "" {
		attrs = append(
			attrs,
			fmt.Sprintf(
				"fg = c.%s",
				h.fg,
			),
		)
	}

	if h.bg != "" {
		attrs = append(
			attrs,
			fmt.Sprintf(
				"bg = c.%s",
				h.bg,
			),
		)
	}

	if h.sp != "" {
		attrs = append(
			attrs,
			fmt.Sprintf(
				"sp = c.%s",
				h.sp,
			),
		)
	}

	if h.cue != "" {
		attrs = append(
			attrs,
			fmt.Sprintf(
				"%s = true",
				h.cue,
			),
		)
	}

	fmt.Fprintf(
		b,
		"set(0, %q, { %s })\n",
		h.group,
		strings.Join(
			attrs,
			", ",
		),
	)
}

func resolveColors(
	p core.Palette,
) (colors, error) {
	derived, err := core.Derive(p)
	if err != nil {
		return colors{}, fmt.Errorf(
			"derive quiet roles: %w",
			err,
		)
	}

	toHex := func(
		name string,
		value color.SRGB,
	) (string, error) {
		result, err := value.Hex()
		if err != nil {
			return "", fmt.Errorf(
				"%s: %w",
				name,
				err,
			)
		}

		return result, nil
	}

	var c colors

	values := []struct {
		name  string
		value color.SRGB
		dst   *string
	}{
		{"Field", p.Anchors.Field, &c.field},
		{"Surface", p.Anchors.Surface, &c.surface},
		{"Structure", p.Anchors.Structure, &c.structure},
		{"Ink", p.Anchors.Ink, &c.ink},
		{"Muted", p.Anchors.Muted, &c.muted},
		{"Line", p.Anchors.Line, &c.line},
		{"Mineral", p.Anchors.Mineral, &c.mineral},
		{"Moss", p.Anchors.Moss, &c.moss},
		{"Ochre", p.Anchors.Ochre, &c.ochre},
		{"Rust", p.Anchors.Rust, &c.rust},
		{"Selection", derived.Selection, &c.selection},
		{"Callout", derived.Callout, &c.callout},
		{"Mineral Wash", derived.Wash.Mineral.Line, &c.mineralWash},
		{"Moss Wash", derived.Wash.Moss.Line, &c.mossWash},
		{"Ochre Wash", derived.Wash.Ochre.Line, &c.ochreWash},
		{"Rust Wash", derived.Wash.Rust.Line, &c.rustWash},
		{"Ochre Wash Emphasis", derived.Wash.Ochre.Emphasis, &c.ochreWashEmphasis},
	}

	for _, item := range values {
		hex, err := toHex(
			item.name,
			item.value,
		)
		if err != nil {
			return colors{}, err
		}

		*item.dst = hex
	}

	term, err := terminal.Resolve(p)
	if err != nil {
		return colors{}, fmt.Errorf(
			"resolve terminal palette: %w",
			err,
		)
	}

	for i, value := range term.ANSI {
		hex, err := toHex(
			fmt.Sprintf("ANSI %d", i),
			value,
		)
		if err != nil {
			return colors{}, err
		}

		c.ansi[i] = hex
	}

	return c, nil
}

func schemeInfo(
	name string,
) (string, string, error) {
	switch name {
	case "quiet-day":
		return "quiet-day", "light", nil
	case "quiet-night":
		return "quiet-night", "dark", nil
	default:
		return "", "", fmt.Errorf(
			"unsupported Neovim palette %q",
			name,
		)
	}
}
