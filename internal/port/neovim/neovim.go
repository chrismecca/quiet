type highlight struct {
	group string
	fg    string
	bg    string
	link  string

	// sp colors an underline or strikethrough.
	sp string

	// cue is a non-color attribute that marks state, such as "underline".
	// quiet keeps a cue only where Neovim's own default for the group has
	// it, and drops typographic emphasis such as bold.
	cue string
}

// Encode writes one quiet palette as a native Neovim Lua colorscheme.
//
// The port controls color. It keeps the non-color cues that mark state in
// Neovim's own defaults, such as underlined diagnostics, in quiet's colors.
// It drops typographic emphasis such as bold keywords and adds no cues of its
// own.
func Encode(
	w io.Writer,
	p core.Palette,
) error {
	name, background, err := schemeInfo(p.Name)
	if err != nil {
		return err
	}

	c, err := resolveColors(p)
	if err != nil {
		return err
	}

	var b strings.Builder

	fmt.Fprintf(
		&b,
		"-- @(#)quiet / lua / ports/neovim/colors/%s.lua / 2026-10-25\n"+
			"--\n"+
			"-- Generated by quiet port neovim. Do not edit.\n"+
			"-- %s\n\n",
		name,
		p.Name,
	)

	b.WriteString("vim.cmd(\"highlight clear\")\n")
	b.WriteString("if vim.fn.exists(\"syntax_on\") == 1 then\n")
	b.WriteString("  vim.cmd(\"syntax reset\")\n")
	b.WriteString("end\n\n")

	fmt.Fprintf(
		&b,
		"vim.o.background = %q\n"+
			"vim.g.colors_name = %q\n\n",
		background,
		name,
	)

	fmt.Fprintf(
		&b,
		"local c = {\n"+
			"  field = %q,\n"+
			"  surface = %q,\n"+
			"  structure = %q,\n"+
			"  ink = %q,\n"+
			"  muted = %q,\n"+
			"  line = %q,\n"+
			"  mineral = %q,\n"+
			"  moss = %q,\n"+
			"  ochre = %q,\n"+
			"  rust = %q,\n"+
			"  selection = %q,\n"+
			"  callout = %q,\n"+
			"  mineral_wash = %q,\n"+
			"  moss_wash = %q,\n"+
			"  ochre_wash = %q,\n"+
			"  rust_wash = %q,\n"+
			"  ochre_wash_emphasis = %q,\n"+
			"}\n\n"+
			"local set = vim.api.nvim_set_hl\n\n",
		c.field,
		c.surface,
		c.structure,
		c.ink,
		c.muted,
		c.line,
		c.mineral,
		c.moss,
		c.ochre,
		c.rust,
		c.selection,
		c.callout,
		c.mineralWash,
		c.mossWash,
		c.ochreWash,
		c.rustWash,
		c.ochreWashEmphasis,
	)

	for _, h := range baseHighlights() {
		writeHighlight(&b, h)
	}

	b.WriteString("\n-- Tree-sitter\n")

	for _, h := range treeSitterHighlights() {
		writeHighlight(&b, h)
	}

	b.WriteString("\n-- Diagnostics\n")

	for _, h := range diagnosticHighlights() {
		writeHighlight(&b, h)
	}

	b.WriteString("\n-- LSP semantic tokens\n")

	for _, h := range lspHighlights() {
		writeHighlight(&b, h)
	}

	b.WriteString("\n-- Terminal, from quiet's generic terminal palette\n")

	for i, hex := range c.ansi {
		fmt.Fprintf(&b, "vim.g.terminal_color_%d = %q\n", i, hex)
	}

	if _, err := io.WriteString(
		w,
		b.String(),
	); err != nil {
		return fmt.Errorf(
			"write Neovim colorscheme: %w",
			err,
		)
	}

	return nil
}

