type colors struct {
	field     string
	surface   string
	structure string
	ink       string
	muted     string
	line      string
	mineral   string
	moss      string
	ochre     string
	rust      string
	selection string
	callout   string
}

type highlight struct {
	group string
	fg    string
	bg    string
	link  string
}

// Encode writes one Quiet palette as a native Neovim Lua colorscheme.
//
// The port controls color only. It deliberately avoids font, weight, italic,
// underline, undercurl, cursor shape, window layout, and other styling policy.
func Encode(
	w io.Writer,
	p core.Palette,
) error {
	name, background, err := schemeInfo(p.Name)
	if err != nil {
		return err
	}

	c, err := resolveColors(p)
	if err != nil {
		return err
	}

	var b strings.Builder

	fmt.Fprintf(
		&b,
		"-- @(#)quiet / lua / ports/neovim/%s.lua / 2026-10-19\n"+
			"--\n"+
			"-- Generated by quiet port neovim. Do not edit.\n"+
			"-- %s\n\n",
		name,
		p.Name,
	)

	b.WriteString("vim.cmd(\"highlight clear\")\n")
	b.WriteString("if vim.fn.exists(\"syntax_on\") == 1 then\n")
	b.WriteString("  vim.cmd(\"syntax reset\")\n")
	b.WriteString("end\n\n")

	fmt.Fprintf(
		&b,
		"vim.o.background = %q\n"+
			"vim.g.colors_name = %q\n\n",
		background,
		name,
	)

	fmt.Fprintf(
		&b,
		"local c = {\n"+
			"  field = %q,\n"+
			"  surface = %q,\n"+
			"  structure = %q,\n"+
			"  ink = %q,\n"+
			"  muted = %q,\n"+
			"  line = %q,\n"+
			"  mineral = %q,\n"+
			"  moss = %q,\n"+
			"  ochre = %q,\n"+
			"  rust = %q,\n"+
			"  selection = %q,\n"+
			"  callout = %q,\n"+
			"}\n\n"+
			"local set = vim.api.nvim_set_hl\n\n",
		c.field,
		c.surface,
		c.structure,
		c.ink,
		c.muted,
		c.line,
		c.mineral,
		c.moss,
		c.ochre,
		c.rust,
		c.selection,
		c.callout,
	)

	for _, h := range baseHighlights() {
		writeHighlight(&b, h)
	}

	b.WriteString("\n-- Tree-sitter\n")

	for _, h := range treeSitterHighlights() {
		writeHighlight(&b, h)
	}

	b.WriteString("\n-- Diagnostics\n")

	for _, h := range diagnosticHighlights() {
		writeHighlight(&b, h)
	}

	b.WriteString("\n-- LSP semantic tokens\n")

	for _, h := range lspHighlights() {
		writeHighlight(&b, h)
	}

	if _, err := io.WriteString(
		w,
		b.String(),
	); err != nil {
		return fmt.Errorf(
			"write Neovim colorscheme: %w",
			err,
		)
	}

	return nil
}

