// Package web exports Quiet Core semantics as CSS custom properties.
package web

import (
	"fmt"
	"io"
	"strings"

	"github.com/chrismecca/quiet/internal/color"
	"github.com/chrismecca/quiet/internal/core"
)

type token struct {
	name  string
	value string
}

type scheme struct {
	colorScheme string
	tokens      []token
}

// EncodeCSS writes a complete Quiet Day/Night CSS custom-property stylesheet.
//
// Quiet Day is the default adaptation. When no explicit data-quiet-theme
// attribute is present, prefers-color-scheme selects Quiet Night for users
// requesting a dark interface.
//
// Explicit data-quiet-theme="day" or data-quiet-theme="night" always wins.
func EncodeCSS(
	w io.Writer,
	day core.Palette,
	night core.Palette,
) error {
	if got := fmt.Sprint(day.Mode); got != "day" {
		return fmt.Errorf(
			"first web palette mode is %q, want %q",
			got,
			"day",
		)
	}

	if got := fmt.Sprint(night.Mode); got != "night" {
		return fmt.Errorf(
			"second web palette mode is %q, want %q",
			got,
			"night",
		)
	}

	dayScheme, err := resolve(
		day,
		"light",
	)
	if err != nil {
		return fmt.Errorf(
			"resolve Quiet Day web scheme: %w",
			err,
		)
	}

	nightScheme, err := resolve(
		night,
		"dark",
	)
	if err != nil {
		return fmt.Errorf(
			"resolve Quiet Night web scheme: %w",
			err,
		)
	}

	var b strings.Builder

	b.WriteString(
		"/* Generated by quiet port web. Do not edit. */\n\n",
	)

	writeRule(
		&b,
		[]string{
			":root",
			"[data-quiet-theme=\"day\"]",
		},
		dayScheme,
		"",
	)

	b.WriteString("\n")
	b.WriteString(
		"@media (prefers-color-scheme: dark) {\n",
	)

	writeRule(
		&b,
		[]string{
			":root:not([data-quiet-theme])",
		},
		nightScheme,
		"  ",
	)

	b.WriteString("}\n\n")

	writeRule(
		&b,
		[]string{
			"[data-quiet-theme=\"night\"]",
		},
		nightScheme,
		"",
	)

	if _, err := io.WriteString(
		w,
		b.String(),
	); err != nil {
		return fmt.Errorf(
			"write web CSS: %w",
			err,
		)
	}

	return nil
}

func resolve(
	p core.Palette,
	colorScheme string,
) (scheme, error) {
	derived, err := core.Derive(p)
	if err != nil {
		return scheme{}, err
	}

	values := []struct {
		name  string
		color color.SRGB
	}{
		{"field", p.Anchors.Field},
		{"surface", p.Anchors.Surface},
		{"structure", p.Anchors.Structure},
		{"ink", p.Anchors.Ink},
		{"muted", p.Anchors.Muted},
		{"line", p.Anchors.Line},
		{"mineral", p.Anchors.Mineral},
		{"moss", p.Anchors.Moss},
		{"ochre", p.Anchors.Ochre},
		{"rust", p.Anchors.Rust},
		{"selection", derived.Selection},
		{"callout", derived.Callout},
		{"mineral-wash", derived.Wash.Mineral.Line},
		{"mineral-wash-emphasis", derived.Wash.Mineral.Emphasis},
		{"moss-wash", derived.Wash.Moss.Line},
		{"moss-wash-emphasis", derived.Wash.Moss.Emphasis},
		{"ochre-wash", derived.Wash.Ochre.Line},
		{"ochre-wash-emphasis", derived.Wash.Ochre.Emphasis},
		{"rust-wash", derived.Wash.Rust.Line},
		{"rust-wash-emphasis", derived.Wash.Rust.Emphasis},
	}

	result := scheme{
		colorScheme: colorScheme,
		tokens:      make([]token, 0, len(values)),
	}

	for _, value := range values {
		hex, err := value.color.Hex()
		if err != nil {
			return scheme{}, fmt.Errorf(
				"%s: %w",
				value.name,
				err,
			)
		}

		result.tokens = append(
			result.tokens,
			token{
				name:  value.name,
				value: hex,
			},
		)
	}

	return result, nil
}

func writeRule(
	b *strings.Builder,
	selectors []string,
	s scheme,
	indent string,
) {
	for i, selector := range selectors {
		b.WriteString(indent)
		b.WriteString(selector)

		if i != len(selectors)-1 {
			b.WriteString(",\n")
			continue
		}

		b.WriteString(" {\n")
	}

	b.WriteString(indent)
	b.WriteString("  color-scheme: ")
	b.WriteString(s.colorScheme)
	b.WriteString(";\n")

	for _, value := range s.tokens {
		b.WriteString(indent)
		b.WriteString("  --quiet-")
		b.WriteString(value.name)
		b.WriteString(": ")
		b.WriteString(value.value)
		b.WriteString(";\n")
	}

	b.WriteString(indent)
	b.WriteString("}\n")
}
