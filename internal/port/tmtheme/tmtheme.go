// Package tmtheme writes quiet as a TextMate .tmTheme property list.
//
// tmTheme is the theme format of Sublime Text, bat, and delta. Syntax rules
// come from the shared textmate policy, so these hosts highlight source
// exactly as quiet's VS Code port does.
package tmtheme

import (
	"encoding/xml"
	"fmt"
	"io"
	"strings"

	"github.com/chrismecca/quiet/internal/color"
	"github.com/chrismecca/quiet/internal/core"
	"github.com/chrismecca/quiet/internal/port/textmate"
)

type setting struct {
	key   string
	value color.SRGB
}

// globals maps the tmTheme editor settings onto quiet roles.
//
// selectionForeground is Ink because quiet-core guarantees only Ink on
// Selection; without it, hosts keep syntax colors such as Mineral, which
// fall below 4.5:1 there.
//
// invisibles is Subtle over Field: whitespace markers are nonessential, and
// the editor ground is fixed, so the contextual role resolves to one color.
func globals(p core.Palette) ([]setting, error) {
	derived, err := core.Derive(p)
	if err != nil {
		return nil, fmt.Errorf(
			"derive quiet roles: %w",
			err,
		)
	}

	subtle, err := core.SubtleOver(
		p,
		p.Anchors.Field,
	)
	if err != nil {
		return nil, err
	}

	a := p.Anchors

	return []setting{
		{"background", a.Field},
		{"foreground", a.Ink},
		{"caret", a.Mineral},
		{"selection", derived.Selection},
		{"selectionForeground", a.Ink},
		{"lineHighlight", derived.Callout},
		{"findHighlight", derived.Callout},
		{"findHighlightForeground", a.Ink},
		{"gutter", a.Field},
		{"gutterForeground", a.Muted},
		{"guide", a.Line},
		{"activeGuide", a.Muted},
		{"invisibles", subtle},
	}, nil
}

// Encode writes p as a tmTheme property list. Hosts name the theme after the
// file, so the artifact is written as <palette name>.tmTheme.
func Encode(
	w io.Writer,
	p core.Palette,
) error {
	settings, err := globals(p)
	if err != nil {
		return err
	}

	var b strings.Builder

	b.WriteString(`<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<!-- Generated by quiet port tmtheme. Do not edit. -->
<plist version="1.0">
<dict>
`)

	writeString(&b, 1, "name", p.Name)
	writeString(&b, 1, "colorSpaceName", "sRGB")

	b.WriteString("\t<key>settings</key>\n\t<array>\n")
	b.WriteString("\t\t<dict>\n\t\t\t<key>settings</key>\n\t\t\t<dict>\n")

	for _, s := range settings {
		hex, err := s.value.Hex()
		if err != nil {
			return fmt.Errorf(
				"tmTheme %s: %w",
				s.key,
				err,
			)
		}

		writeString(&b, 4, s.key, hex)
	}

	b.WriteString("\t\t\t</dict>\n\t\t</dict>\n")

	rules := append(
		textmate.SourceRules(p),
		textmate.DiffRules(p)...,
	)

	for _, rule := range rules {
		hex, err := rule.Color.Hex()
		if err != nil {
			return fmt.Errorf(
				"tmTheme rule %s: %w",
				rule.Name,
				err,
			)
		}

		b.WriteString("\t\t<dict>\n")
		writeString(&b, 3, "name", rule.Name)
		writeString(&b, 3, "scope", strings.Join(rule.Scopes, ", "))
		b.WriteString("\t\t\t<key>settings</key>\n\t\t\t<dict>\n")
		writeString(&b, 4, "foreground", hex)
		b.WriteString("\t\t\t</dict>\n\t\t</dict>\n")
	}

	b.WriteString("\t</array>\n</dict>\n</plist>\n")

	if _, err := io.WriteString(
		w,
		b.String(),
	); err != nil {
		return fmt.Errorf(
			"write tmTheme: %w",
			err,
		)
	}

	return nil
}

// writeString writes one plist key and string value at the given tab depth.
func writeString(
	b *strings.Builder,
	depth int,
	key string,
	value string,
) {
	indent := strings.Repeat("\t", depth)

	b.WriteString(indent)
	b.WriteString("<key>")
	xml.EscapeText(b, []byte(key))
	b.WriteString("</key>\n")
	b.WriteString(indent)
	b.WriteString("<string>")
	xml.EscapeText(b, []byte(value))
	b.WriteString("</string>\n")
}
