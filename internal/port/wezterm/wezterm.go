// Package wezterm serializes quiet's generic terminal palette into WezTerm's
// native TOML color-scheme format.
package wezterm

import (
	"fmt"
	"io"
	"strings"

	"github.com/chrismecca/quiet/internal/color"
	"github.com/chrismecca/quiet/internal/port/terminal"
)

const originURL = "https://github.com/chrismecca/quiet"

// Encode writes one resolved generic terminal palette as a WezTerm TOML
// color-scheme file.
//
// This package contains no quiet color derivation. Semantic mapping and ANSI
// derivation occur in terminal.Resolve before the palette reaches this
// serializer.
func Encode(
	w io.Writer,
	p terminal.Palette,
) error {
	foreground, err := hex("foreground", p.Text)
	if err != nil {
		return err
	}

	background, err := hex("background", p.Background)
	if err != nil {
		return err
	}

	cursor, err := hex("cursor", p.Cursor)
	if err != nil {
		return err
	}

	selection, err := hex("selection", p.Selection)
	if err != nil {
		return err
	}

	ansi, err := paletteArray(p.ANSI[:8])
	if err != nil {
		return fmt.Errorf("ANSI: %w", err)
	}

	brights, err := paletteArray(p.ANSI[8:])
	if err != nil {
		return fmt.Errorf("brights: %w", err)
	}

	var b strings.Builder

	fmt.Fprintf(
		&b,
		"# Generated by quiet port wezterm. Do not edit.\n"+
			"#\n"+
			"# %s\n\n",
		p.Name,
	)

	fmt.Fprintf(
		&b,
		"[colors]\n"+
			"foreground = %q\n"+
			"background = %q\n"+
			"cursor_bg = %q\n"+
			"cursor_border = %q\n"+
			"cursor_fg = %q\n"+
			"selection_bg = %q\n"+
			"selection_fg = %q\n"+
			"ansi = [%s]\n"+
			"brights = [%s]\n"+
			"\n"+
			"[metadata]\n"+
			"name = %q\n"+
			"origin_url = %q\n",
		foreground,
		background,
		cursor,
		cursor,
		background,
		selection,
		foreground,
		ansi,
		brights,
		p.Name,
		originURL,
	)

	if _, err := io.WriteString(
		w,
		b.String(),
	); err != nil {
		return fmt.Errorf(
			"write WezTerm theme: %w",
			err,
		)
	}

	return nil
}

func paletteArray(
	values []color.SRGB,
) (string, error) {
	items := make(
		[]string,
		0,
		len(values),
	)

	for i, value := range values {
		valueHex, err := value.Hex()
		if err != nil {
			return "", fmt.Errorf(
				"color %d: %w",
				i,
				err,
			)
		}

		items = append(
			items,
			fmt.Sprintf(
				"%q",
				valueHex,
			),
		)
	}

	return strings.Join(
		items,
		", ",
	), nil
}

func hex(
	name string,
	value color.SRGB,
) (string, error) {
	result, err := value.Hex()
	if err != nil {
		return "", fmt.Errorf(
			"%s: %w",
			name,
			err,
		)
	}

	return result, nil
}
