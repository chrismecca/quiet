// role is one named color the theme binds in its let form.
type role struct {
	name  string
	value color.SRGB
}

// face sets one Emacs face. Colors are role names.
type face struct {
	name       string
	foreground string
	background string

	// underline keeps an underline Emacs's own default gives the face:
	// "line", or "wave" in the color underlineColor.
	underline      string
	underlineColor string

	// extend carries a region's background to the window edge, as Emacs's
	// default diff faces do.
	extend bool

	// inherit names a face this one inherits from, as in Emacs's default.
	inherit string
}

// Encode writes one quiet palette as a native Emacs theme.
//
// The port controls color. It keeps the underlines Emacs's own defaults give
// links and diagnostics, in quiet's colors, and the :extend of diff regions.
// It drops typographic emphasis such as bold, and sets no font family,
// height, slant, or boxes.
func Encode(
	w io.Writer,
	p core.Palette,
) error {
	theme, err := themeSymbol(p.Name)
	if err != nil {
		return err
	}

	backgroundMode, err := themeBackgroundMode(p.Mode)
	if err != nil {
		return err
	}

	roles, err := resolveRoles(p)
	if err != nil {
		return err
	}

	var b strings.Builder

	fmt.Fprintf(
		&b,
		";;; %s-theme.el --- quiet color theme -*- lexical-binding: t; -*-\n"+
			";;\n"+
			";; Generated by quiet port emacs. Do not edit.\n"+
			";;\n\n"+
			";;;###autoload\n"+
			"(deftheme %s\n"+
			"  %q\n"+
			"  :background-mode '%s\n"+
			"  :kind 'color-scheme\n"+
			"  :family 'quiet)\n\n",
		theme,
		theme,
		p.Name+" — a restrained color system for long-duration work.",
		backgroundMode,
	)

	for i, r := range roles {
		prefix := "      "
		if i == 0 {
			prefix = "(let ("
		}

		suffix := ""
		if i == len(roles)-1 {
			suffix = ")"
		}

		fmt.Fprintf(
			&b,
			"%s(%s %q)%s\n",
			prefix,
			r.name,
			r.value.MustHex(),
			suffix,
		)
	}

	fmt.Fprintf(
		&b,
		"  (custom-theme-set-faces\n"+
			"   '%s\n",
		theme,
	)

	for _, f := range faces() {
		writeFace(
			&b,
			f,
		)
	}

	b.WriteString("   ))\n\n")

	fmt.Fprintf(
		&b,
		"(provide-theme '%s)\n\n"+
			";;; %s-theme.el ends here\n",
		theme,
		theme,
	)

	if _, err := io.WriteString(
		w,
		b.String(),
	); err != nil {
		return fmt.Errorf(
			"write Emacs theme: %w",
			err,
		)
	}

	return nil
}

