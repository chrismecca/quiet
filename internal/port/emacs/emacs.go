// Package emacs maps Quiet Core semantics onto GNU Emacs faces.
package emacs

import (
	"fmt"
	"io"
	"strings"

	"github.com/chrismecca/quiet/internal/color"
	"github.com/chrismecca/quiet/internal/core"
)

type colors struct {
	field     string
	surface   string
	structure string
	ink       string
	muted     string
	line      string
	mineral   string
	moss      string
	ochre     string
	rust      string
	selection string
	callout   string
}

type face struct {
	name       string
	foreground string
	background string
}

// Encode writes one Quiet palette as a native Emacs theme.
//
// The port defines color only. It deliberately does not set font family,
// height, weight, slant, underline, boxes, or other typography/decorative
// policy.
func Encode(
	w io.Writer,
	p core.Palette,
) error {
	theme, err := themeSymbol(p.Name)
	if err != nil {
		return err
	}

	backgroundMode, err := themeBackgroundMode(p.Mode)
	if err != nil {
		return err
	}

	c, err := resolveColors(p)
	if err != nil {
		return err
	}

	faces := []face{
		{"default", c.ink, c.field},
		{"cursor", "", c.mineral},
		{"region", c.ink, c.selection},
		{"highlight", c.ink, c.callout},
		{"secondary-selection", c.ink, c.callout},

		{"shadow", c.muted, ""},
		{"fringe", c.muted, c.field},
		{"vertical-border", c.line, ""},
		{"window-divider", c.line, ""},
		{"window-divider-first-pixel", c.line, ""},
		{"window-divider-last-pixel", c.line, ""},

		{"header-line", c.ink, c.surface},
		{"mode-line", c.ink, c.structure},
		{"mode-line-inactive", c.muted, c.surface},
		{"mode-line-emphasis", c.mineral, ""},
		{"mode-line-highlight", c.ink, c.callout},

		{"line-number", c.muted, c.field},
		{"line-number-current-line", c.mineral, c.field},

		{"minibuffer-prompt", c.mineral, ""},
		{"link", c.mineral, ""},
		{"link-visited", c.mineral, ""},
		{"button", c.mineral, ""},

		{"success", c.moss, ""},
		{"warning", c.ochre, ""},
		{"error", c.rust, ""},

		{"isearch", c.ink, c.selection},
		{"lazy-highlight", c.ink, c.callout},
		{"match", c.ink, c.selection},
		{"isearch-fail", c.rust, c.callout},

		{"show-paren-match", c.ink, c.selection},
		{"show-paren-mismatch", c.rust, c.callout},

		{"font-lock-builtin-face", c.mineral, ""},
		{"font-lock-comment-face", c.muted, ""},
		{"font-lock-comment-delimiter-face", c.muted, ""},
		{"font-lock-constant-face", c.ink, ""},
		{"font-lock-doc-face", c.muted, ""},
		{"font-lock-function-name-face", c.ink, ""},
		{"font-lock-keyword-face", c.mineral, ""},
		{"font-lock-negation-char-face", c.mineral, ""},
		{"font-lock-preprocessor-face", c.mineral, ""},
		{"font-lock-regexp-grouping-backslash", c.mineral, ""},
		{"font-lock-regexp-grouping-construct", c.mineral, ""},
		{"font-lock-string-face", c.ink, ""},
		{"font-lock-type-face", c.mineral, ""},
		{"font-lock-variable-name-face", c.ink, ""},
		{"font-lock-warning-face", c.ochre, ""},

		{"completions-common-part", c.mineral, ""},
		{"completions-first-difference", c.ink, ""},
	}

	var b strings.Builder

	fmt.Fprintf(
		&b,
		";;; %s-theme.el --- Quiet color theme -*- lexical-binding: t; -*-\n"+
			";;\n"+
			";; Generated by quiet port emacs. Do not edit.\n"+
			";;\n\n"+
			";;;###autoload\n"+
			"(deftheme %s\n"+
			"  %q\n"+
			"  :background-mode '%s\n"+
			"  :kind 'color-scheme\n"+
			"  :family 'quiet)\n\n",
		theme,
		theme,
		p.Name+" — a restrained color system for long-duration work.",
		backgroundMode,
	)

	fmt.Fprintf(
		&b,
		"(let ((field %q)\n"+
			"      (surface %q)\n"+
			"      (structure %q)\n"+
			"      (ink %q)\n"+
			"      (muted %q)\n"+
			"      (line %q)\n"+
			"      (mineral %q)\n"+
			"      (moss %q)\n"+
			"      (ochre %q)\n"+
			"      (rust %q)\n"+
			"      (selection %q)\n"+
			"      (callout %q))\n"+
			"  (custom-theme-set-faces\n"+
			"   '%s\n",
		c.field,
		c.surface,
		c.structure,
		c.ink,
		c.muted,
		c.line,
		c.mineral,
		c.moss,
		c.ochre,
		c.rust,
		c.selection,
		c.callout,
		theme,
	)

	for _, f := range faces {
		writeFace(
			&b,
			f,
			c,
		)
	}

	b.WriteString("   ))\n\n")

	fmt.Fprintf(
		&b,
		"(provide-theme '%s)\n\n"+
			";;; %s-theme.el ends here\n",
		theme,
		theme,
	)

	if _, err := io.WriteString(
		w,
		b.String(),
	); err != nil {
		return fmt.Errorf(
			"write Emacs theme: %w",
			err,
		)
	}

	return nil
}

func writeFace(
	b *strings.Builder,
	f face,
	c colors,
) {
	var attrs []string

	if f.foreground != "" {
		attrs = append(
			attrs,
			fmt.Sprintf(
				":foreground ,%s",
				colorVariable(
					f.foreground,
					c,
				),
			),
		)
	}

	if f.background != "" {
		attrs = append(
			attrs,
			fmt.Sprintf(
				":background ,%s",
				colorVariable(
					f.background,
					c,
				),
			),
		)
	}

	fmt.Fprintf(
		b,
		"   `(%s ((t (%s))))\n",
		f.name,
		strings.Join(
			attrs,
			" ",
		),
	)
}

func colorVariable(
	value string,
	c colors,
) string {
	switch value {
	case c.field:
		return "field"

	case c.surface:
		return "surface"

	case c.structure:
		return "structure"

	case c.ink:
		return "ink"

	case c.muted:
		return "muted"

	case c.line:
		return "line"

	case c.mineral:
		return "mineral"

	case c.moss:
		return "moss"

	case c.ochre:
		return "ochre"

	case c.rust:
		return "rust"

	case c.selection:
		return "selection"

	case c.callout:
		return "callout"

	default:
		panic(
			"Emacs face references unknown Quiet color",
		)
	}
}

func resolveColors(
	p core.Palette,
) (colors, error) {
	derived, err := core.Derive(p)
	if err != nil {
		return colors{}, fmt.Errorf(
			"derive Quiet roles: %w",
			err,
		)
	}

	c := colors{}

	values := []struct {
		name  string
		value color.SRGB
		dst   *string
	}{
		{"Field", p.Anchors.Field, &c.field},
		{"Surface", p.Anchors.Surface, &c.surface},
		{"Structure", p.Anchors.Structure, &c.structure},
		{"Ink", p.Anchors.Ink, &c.ink},
		{"Muted", p.Anchors.Muted, &c.muted},
		{"Line", p.Anchors.Line, &c.line},
		{"Mineral", p.Anchors.Mineral, &c.mineral},
		{"Moss", p.Anchors.Moss, &c.moss},
		{"Ochre", p.Anchors.Ochre, &c.ochre},
		{"Rust", p.Anchors.Rust, &c.rust},
		{"Selection", derived.Selection, &c.selection},
		{"Callout", derived.Callout, &c.callout},
	}

	for _, item := range values {
		hex, err := item.value.Hex()
		if err != nil {
			return colors{}, fmt.Errorf(
				"%s: %w",
				item.name,
				err,
			)
		}

		*item.dst = hex
	}

	return c, nil
}

func themeSymbol(
	name string,
) (string, error) {
	switch name {
	case "Quiet Day":
		return "quiet-day", nil

	case "Quiet Night":
		return "quiet-night", nil

	default:
		return "", fmt.Errorf(
			"unsupported Emacs theme palette %q",
			name,
		)
	}
}

func themeBackgroundMode(
	mode core.Mode,
) (string, error) {
	switch mode {
	case core.ModeDay:
		return "light", nil

	case core.ModeNight:
		return "dark", nil

	default:
		return "", fmt.Errorf(
			"unsupported Emacs palette mode %q",
			mode,
		)
	}
}
