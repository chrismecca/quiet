func writeFace(
	b *strings.Builder,
	f face,
) {
	var attrs []string

	if f.inherit != "" {
		attrs = append(
			attrs,
			":inherit "+f.inherit,
		)
	}

	if f.foreground != "" {
		attrs = append(
			attrs,
			":foreground ,"+f.foreground,
		)
	}

	if f.background != "" {
		attrs = append(
			attrs,
			":background ,"+f.background,
		)
	}

	switch f.underline {
	case "line":
		attrs = append(
			attrs,
			":underline t",
		)

	case "wave":
		attrs = append(
			attrs,
			":underline (:style wave :color ,"+f.underlineColor+")",
		)
	}

	if f.extend {
		attrs = append(
			attrs,
			":extend t",
		)
	}

	fmt.Fprintf(
		b,
		"   `(%s ((t (%s))))\n",
		f.name,
		strings.Join(
			attrs,
			" ",
		),
	)
}

// resolveRoles returns every color the theme binds, in binding order.
func resolveRoles(
	p core.Palette,
) ([]role, error) {
	derived, err := core.Derive(p)
	if err != nil {
		return nil, fmt.Errorf(
			"derive quiet roles: %w",
			err,
		)
	}

	term, err := terminal.Resolve(p)
	if err != nil {
		return nil, fmt.Errorf(
			"resolve terminal palette: %w",
			err,
		)
	}

	a := p.Anchors
	wash := derived.Wash

	roles := []role{
		{"field", a.Field},
		{"surface", a.Surface},
		{"structure", a.Structure},
		{"ink", a.Ink},
		{"muted", a.Muted},
		{"line", a.Line},
		{"mineral", a.Mineral},
		{"moss", a.Moss},
		{"ochre", a.Ochre},
		{"rust", a.Rust},
		{"selection", derived.Selection},
		{"callout", derived.Callout},
		{"mineral-wash", wash.Mineral.Line},
		{"moss-wash", wash.Moss.Line},
		{"ochre-wash", wash.Ochre.Line},
		{"rust-wash", wash.Rust.Line},
		{"mineral-wash-emphasis", wash.Mineral.Emphasis},
		{"moss-wash-emphasis", wash.Moss.Emphasis},
		{"ochre-wash-emphasis", wash.Ochre.Emphasis},
		{"rust-wash-emphasis", wash.Rust.Emphasis},
	}

	for i, c := range term.ANSI {
		roles = append(
			roles,
			role{fmt.Sprintf("ansi-%d", i), c},
		)
	}

	for _, r := range roles {
		if _, err := r.value.Hex(); err != nil {
			return nil, fmt.Errorf(
				"%s: %w",
				r.name,
				err,
			)
		}
	}

	return roles, nil
}

func themeSymbol(
	name string,
) (string, error) {
	switch name {
	case "quiet-day":
		return "quiet-day", nil

	case "quiet-night":
		return "quiet-night", nil

	default:
		return "", fmt.Errorf(
			"unsupported Emacs theme palette %q",
			name,
		)
	}
}

func themeBackgroundMode(
	mode core.Mode,
) (string, error) {
	switch mode {
	case core.ModeDay:
		return "light", nil

	case core.ModeNight:
		return "dark", nil

	default:
		return "", fmt.Errorf(
			"unsupported Emacs palette mode %q",
			mode,
		)
	}
}
