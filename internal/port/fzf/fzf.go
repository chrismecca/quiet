// Package fzf maps quiet-core semantics onto fzf's color names.
//
// The port writes an options file for FZF_DEFAULT_OPTS_FILE containing only
// --color options. It does not configure layout, key bindings, previews, or
// search behavior.
package fzf

import (
	"fmt"
	"io"
	"strings"

	"github.com/chrismecca/quiet/internal/color"
	"github.com/chrismecca/quiet/internal/core"
)

// role names a quiet color used by the fzf mapping.
type role int

const (
	field role = iota
	surface
	ink
	muted
	line
	mineral
	ochre
	selection
	callout
)

type palette [callout + 1]color.SRGB

func resolve(p core.Palette) (palette, error) {
	derived, err := core.Derive(p)
	if err != nil {
		return palette{}, fmt.Errorf(
			"derive quiet roles: %w",
			err,
		)
	}

	return palette{
		field:     p.Anchors.Field,
		surface:   p.Anchors.Surface,
		ink:       p.Anchors.Ink,
		muted:     p.Anchors.Muted,
		line:      p.Anchors.Line,
		mineral:   p.Anchors.Mineral,
		ochre:     p.Anchors.Ochre,
		selection: derived.Selection,
		callout:   derived.Callout,
	}, nil
}

// entry maps one fzf color name onto a quiet role. attributes are fzf ANSI
// attributes; "regular" first clears any attribute inherited from the base
// scheme.
type entry struct {
	name       string
	role       role
	attributes []string
}

type section struct {
	comment string
	entries []entry
}

// mapping is the complete fzf policy. fzf color names inherit from their
// parents, so children are listed only where their meaning differs.
//
// Matches on the current line are Ink in bold rather than Mineral: Mineral on
// Selection falls below 4.5:1, and quiet-core guarantees only Ink there.
// Typography carries the match instead of hue.
var mapping = []section{
	{
		comment: "List.",
		entries: []entry{
			{name: "fg", role: ink},
			{name: "bg", role: field},
			{name: "gutter", role: field},
			{name: "hl", role: mineral},
		},
	},
	{
		comment: "Current line.",
		entries: []entry{
			{name: "fg+", role: ink, attributes: []string{"regular"}},
			{name: "bg+", role: selection},
			{name: "hl+", role: ink, attributes: []string{"regular", "bold"}},
			{name: "pointer", role: mineral},
		},
	},
	{
		comment: "Multi-select.",
		entries: []entry{
			{name: "selected-bg", role: callout},
			{name: "marker", role: ochre},
		},
	},
	{
		comment: "Input and status.",
		entries: []entry{
			{name: "query", role: ink},
			{name: "prompt", role: mineral},
			{name: "ghost", role: muted},
			{name: "disabled", role: muted},
			{name: "info", role: muted},
			{name: "spinner", role: mineral},
		},
	},
	{
		comment: "Preview.",
		entries: []entry{
			{name: "preview-bg", role: surface},
			{name: "preview-fg", role: ink},
			{name: "preview-scrollbar", role: muted},
		},
	},
	{
		comment: "Borders and labels.",
		entries: []entry{
			{name: "border", role: line},
			{name: "separator", role: line},
			{name: "scrollbar", role: muted},
			{name: "label", role: muted},
		},
	},
	{
		comment: "Header and footer.",
		entries: []entry{
			{name: "header", role: muted},
			{name: "footer", role: muted},
		},
	},
}

// Encode writes an fzf options file for p.
//
// The base scheme matches the adaptation so any fzf element quiet does not
// map still suits the background.
func Encode(
	w io.Writer,
	p core.Palette,
) error {
	resolved, err := resolve(p)
	if err != nil {
		return err
	}

	var base string

	switch p.Mode {
	case core.ModeDay:
		base = "light"

	case core.ModeNight:
		base = "dark"

	default:
		return fmt.Errorf(
			"unsupported fzf palette mode %q",
			p.Mode,
		)
	}

	var b strings.Builder

	fmt.Fprintf(
		&b,
		`# Generated by quiet port fzf. Do not edit.
#
# %s
#
# quiet color options for fzf. Load with:
#
#   export FZF_DEFAULT_OPTS_FILE=/path/to/%s.fzfrc
#
# This file sets colors only.

# Base scheme.
--color=%s
`,
		p.Name,
		p.Name,
		base,
	)

	for _, s := range mapping {
		fmt.Fprintf(
			&b,
			"\n# %s\n",
			s.comment,
		)

		for _, e := range s.entries {
			hex, err := resolved[e.role].Hex()
			if err != nil {
				return fmt.Errorf(
					"fzf %s: %w",
					e.name,
					err,
				)
			}

			value := append(
				[]string{e.name, hex},
				e.attributes...,
			)

			fmt.Fprintf(
				&b,
				"--color=%s\n",
				strings.Join(value, ":"),
			)
		}
	}

	if _, err := io.WriteString(
		w,
		b.String(),
	); err != nil {
		return fmt.Errorf(
			"write fzf options: %w",
			err,
		)
	}

	return nil
}
