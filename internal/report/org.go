// Package report computes quiet's analytical evidence as Org tables.
//
// The tables are generated artifacts. Authored report prose under
// reports/src includes them, so every number a report cites is reproduced by
// the reference implementation rather than copied by hand.
package report

import (
	"fmt"
	"strings"
	"unicode/utf8"

	"github.com/chrismecca/quiet/internal/color"
)

// Table is one generated Org table. Name is the file stem under
// reports/data.
type Table struct {
	Name string
	Org  string
}

type orgTable struct {
	header []string
	rows   [][]string
}

// render writes an aligned Org table. Alignment is cosmetic for Org itself
// but keeps the committed artifacts readable as plain text.
func (t orgTable) render(name string) Table {
	widths := make([]int, len(t.header))

	for _, row := range append([][]string{t.header}, t.rows...) {
		for i, cell := range row {
			if n := utf8.RuneCountInString(cell); n > widths[i] {
				widths[i] = n
			}
		}
	}

	var b strings.Builder

	writeRow := func(row []string) {
		b.WriteString("|")

		for i, cell := range row {
			b.WriteString(" ")
			b.WriteString(cell)
			b.WriteString(strings.Repeat(
				" ",
				widths[i]-utf8.RuneCountInString(cell),
			))
			b.WriteString(" |")
		}

		b.WriteString("\n")
	}

	writeRow(t.header)

	b.WriteString("|")

	for i, w := range widths {
		b.WriteString(strings.Repeat("-", w+2))

		if i != len(widths)-1 {
			b.WriteString("+")
		}
	}

	b.WriteString("|\n")

	for _, row := range t.rows {
		writeRow(row)
	}

	// The marker follows the table: an Org caption placed before an
	// #+INCLUDE must be directly followed by the table it describes.
	b.WriteString("# Generated by quiet report. Do not edit.\n")

	return Table{
		Name: name,
		Org:  b.String(),
	}
}

// swatch emits a LaTeX export snippet. The report preamble defines \swatch;
// other Org exporters drop the snippet and keep the hexadecimal column.
func swatch(c color.SRGB) string {
	return fmt.Sprintf(
		`@@latex:\swatch{%s}@@`,
		strings.TrimPrefix(c.MustHex(), "#"),
	)
}

func ratio(x float64) string {
	return fmt.Sprintf("%.2f", x)
}

func margin(x float64) string {
	return fmt.Sprintf("%+.2f", x)
}

func distance(x float64) string {
	return fmt.Sprintf("%.3f", x)
}

// prose turns a role or family identifier into its capitalized prose form,
// following the project naming convention: "moss-wash" becomes "Moss wash".
func prose(id string) string {
	words := strings.ReplaceAll(id, "-", " ")

	if words == "" {
		return words
	}

	return strings.ToUpper(words[:1]) + words[1:]
}
